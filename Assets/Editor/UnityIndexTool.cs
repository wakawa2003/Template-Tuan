using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Threading;
using UnityEditor;
using UnityEngine;

namespace RingOut.EditorTools
{
    /// <summary>
    /// Drives the Unity object index (tools/unity_*.py) from inside the editor.
    ///
    /// Menu Tools/Unity Index:
    ///  - Setup In This Project : copy the three python scripts (asks for a folder
    ///    when they are missing), install git hooks, add .unity-index/ to
    ///    .gitignore and build the index once;
    ///  - Rebuild Index         : re-parse every .asset/.prefab/.unity;
    ///  - Status                : index age/size, lock, hooks;
    ///  - Export To Another Project : copy the toolchain (scripts + this menu)
    ///    into another Unity project and initialise it there.
    ///
    /// The index itself lives in &lt;project&gt;/.unity-index/index.json and is
    /// gitignored: it is derived data, rebuilt from the YAML in about 5 seconds.
    /// </summary>
    public static class UnityIndexTool
    {
        const string Root = "Tools/Unity Index/";
        const string AutoRefreshItem = Root + "Auto Refresh On Save";
        internal const string AutoRefreshKey = "RingOut.UnityIndex.AutoRefresh";
        const string PythonKey = "RingOut.UnityIndex.Python";
        const string ScriptProbe =
            "-c \"import sys, yaml; print(sys.version.split()[0], 'pyyaml', yaml.__version__)\"";

        const string GitIgnoreBlock =
            "# Unity object index (generated by tools/unity_object_index.py)\n.unity-index/\n";

        static readonly string ProjectRoot = Directory.GetParent(Application.dataPath).FullName;
        static readonly string ToolsDir = Path.Combine(ProjectRoot, "tools");
        static readonly string IndexDir = Path.Combine(ProjectRoot, ".unity-index");
        static readonly string IndexFile = Path.Combine(IndexDir, "index.json");
        static readonly string RefreshLog = Path.Combine(IndexDir, "refresh.log");

        static readonly string[] ToolFiles = { "unity_object_index.py", "unity_query.py", "unity_refresh.py" };
        static readonly string[] UnityExtensions = { ".asset", ".prefab", ".unity" };

        static string s_python;
        static string s_pythonArgs;
        static bool s_busy;
        static bool s_missingWarned;
        static double s_refreshAt = -1;
        static readonly ConcurrentQueue<Action> s_mainThread = new ConcurrentQueue<Action>();

        [InitializeOnLoadMethod]
        static void Wire()
        {
            EditorApplication.update += Pump;
        }

        static void Pump()
        {
            Action action;
            while (s_mainThread.TryDequeue(out action))
            {
                try { action(); }
                catch (Exception e) { Debug.LogException(e); }
            }

            if (s_refreshAt > 0 && EditorApplication.timeSinceStartup >= s_refreshAt)
            {
                s_refreshAt = -1;
                if (EditorPrefs.GetBool(AutoRefreshKey, false)
                    && !s_busy
                    && !EditorApplication.isPlayingOrWillChangePlaymode
                    && !EditorApplication.isCompiling)
                    Rebuild(true);
            }
        }

        #region Menu

        [MenuItem(Root + "Setup In This Project", false, 0)]
        static void Setup()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode)
            {
                EditorUtility.DisplayDialog("Unity Index", "Stop play mode first.", "OK");
                return;
            }

            if (!EnsureToolFiles())
                return;

            if (!ResolvePython(out string probe))
            {
                EditorUtility.DisplayDialog("Unity Index", probe, "OK");
                return;
            }

            Debug.Log($"[unity-index] {probe}");
            EnsureGitIgnore(ProjectRoot);

            RunPythonAsync("Building index...", "unity_object_index.py", string.Empty, ProjectRoot, (code, output) =>
            {
                Debug.Log($"[unity-index] build\n{output}");
                if (code != 0)
                {
                    EditorUtility.DisplayDialog("Unity Index", "Index build failed - see the Console.", "OK");
                    return;
                }

                RunPythonAsync("Installing git hooks...", "unity_refresh.py", "--install-hooks", ProjectRoot, (hookCode, hookOutput) =>
                {
                    Debug.Log($"[unity-index] hooks\n{hookOutput}");
                    EditorUtility.DisplayDialog(
                        "Unity Index",
                        (hookCode == 0 ? "Index ready." : "Index built, but git hooks failed - see the Console.")
                        + $"\n\n{IndexFile}\n\nThe agent now answers prefab/scene questions with\npython tools/unity_query.py",
                        "OK");
                    EditorUtility.RevealInFinder(IndexFile);
                });
            });
        }

        [MenuItem(Root + "Rebuild Index", false, 1)]
        static void RebuildMenu()
        {
            Rebuild(false);
        }

        static void Rebuild(bool silent)
        {
            if (s_busy)
                return;
            if (!EnsureToolFiles(silent))
                return;

            RunPythonAsync("Building index...", "unity_object_index.py", string.Empty, ProjectRoot, (code, output) =>
            {
                Debug.Log($"[unity-index] build\n{output}");
                if (code != 0 && !silent)
                    EditorUtility.DisplayDialog("Unity Index", "Index build failed - see the Console.", "OK");
            });
        }

        [MenuItem(Root + "Update Toolchain Scripts", false, 3)]
        static void UpdateScripts()
        {
            if (!WriteEmbeddedToolchain(true))
            {
                EditorUtility.DisplayDialog("Unity Index", "Could not write tools/*.py - see the Console.", "OK");
                return;
            }

            Debug.Log($"[unity-index] tools/*.py rewritten from the package into {ToolsDir}");
            EditorUtility.DisplayDialog("Unity Index", $"Scripts updated:\n{ToolsDir}", "OK");
        }

        [MenuItem(Root + "Status", false, 2)]
        static void Status()
        {
            if (!EnsureToolFiles(false))
                return;
            if (!ResolvePython(out string probe))
            {
                EditorUtility.DisplayDialog("Unity Index", probe, "OK");
                return;
            }

            var result = RunSync(s_python, ScriptArg("unity_refresh.py", "--status"), 30000, ProjectRoot);
            Debug.Log($"[unity-index] status\n{result.output}");
            EditorUtility.DisplayDialog("Unity Index", result.output, "OK");
        }

        [MenuItem(Root + "Open Index Folder", false, 10)]
        static void OpenFolder()
        {
            Directory.CreateDirectory(IndexDir);
            EditorUtility.RevealInFinder(IndexFile);
        }

        [MenuItem(Root + "Show Refresh Log", false, 11)]
        static void ShowLog()
        {
            if (File.Exists(RefreshLog))
                EditorUtility.OpenWithDefaultApp(RefreshLog);
            else
                EditorUtility.DisplayDialog("Unity Index", $"No log yet:\n{RefreshLog}", "OK");
        }

        [MenuItem(Root + "Export To Another Project...", false, 20)]
        static void Export()
        {
            if (!EnsureToolFiles(false))
                return;

            string target = EditorUtility.OpenFolderPanel(
                "Choose the target Unity project root", Path.GetDirectoryName(ProjectRoot), string.Empty);
            if (string.IsNullOrEmpty(target))
                return;

            if (!Directory.Exists(Path.Combine(target, "Assets")))
            {
                EditorUtility.DisplayDialog("Unity Index", $"{target}\nhas no Assets/ folder - not a Unity project.", "OK");
                return;
            }

            try
            {
                CopyToolchain(target);
            }
            catch (Exception e)
            {
                EditorUtility.DisplayDialog("Unity Index", $"Copy failed:\n{e.Message}", "OK");
                return;
            }

            if (!ResolvePython(out string probe))
            {
                EditorUtility.DisplayDialog("Unity Index", probe, "OK");
                return;
            }

            RunPythonAsync("Building index in the target project...", "unity_object_index.py", string.Empty, target, (code, output) =>
            {
                Debug.Log($"[unity-index] target build\n{output}");
                if (code != 0)
                {
                    EditorUtility.DisplayDialog("Unity Index", "Target index build failed - see the Console.", "OK");
                    return;
                }

                RunPythonAsync("Installing git hooks in the target...", "unity_refresh.py", "--install-hooks", target, (hookCode, hookOutput) =>
                {
                    Debug.Log($"[unity-index] target hooks\n{hookOutput}");
                    EditorUtility.DisplayDialog(
                        "Unity Index",
                        $"Installed into:\n{target}\n\nThe same menu now exists there (Tools/Unity Index).\n"
                        + "Add the AGENTS.md snippet from tools/unity_index_install.py to that project.",
                        "OK");
                });
            });
        }

        [MenuItem(Root + "Set Python Path...", false, 30)]
        static void SetPythonPath()
        {
            string current = EditorPrefs.GetString(PythonKey, string.Empty);
            string picked = EditorUtility.OpenFilePanel(
                "Choose the Python executable", Path.GetDirectoryName(current), string.Empty);
            if (string.IsNullOrEmpty(picked))
                return;

            EditorPrefs.SetString(PythonKey, picked);
            s_python = null;
            s_pythonArgs = null;

            if (ResolvePython(out string probe))
                Debug.Log($"[unity-index] {probe}");
            else
                Debug.LogWarning($"[unity-index] {probe}");
        }

        [MenuItem(AutoRefreshItem, true, 31)]
        static bool AutoRefreshValidate()
        {
            Menu.SetChecked(AutoRefreshItem, EditorPrefs.GetBool(AutoRefreshKey, false));
            return true;
        }

        [MenuItem(AutoRefreshItem, false, 31)]
        static void AutoRefreshToggle()
        {
            bool enabled = !EditorPrefs.GetBool(AutoRefreshKey, false);
            EditorPrefs.SetBool(AutoRefreshKey, enabled);
            Debug.Log(enabled
                ? "[unity-index] auto refresh on save: ON (index rebuilds ~4s after each prefab/scene/asset save)"
                : "[unity-index] auto refresh on save: OFF");
        }

        #endregion

        #region Automation

        /// <summary>
        /// Batch mode entry point, for CI or a scripted first setup:
        /// Unity -batchmode -quit -projectPath &lt;dir&gt; -importPackage UnityObjectIndex.unitypackage
        ///       -executeMethod RingOut.EditorTools.UnityIndexTool.InstallFromCommandLine
        /// Exits 0 on success, 1 when the scripts cannot be written, 2 when Python/PyYAML is missing.
        /// </summary>
        public static void InstallFromCommandLine()
        {
            if (!EnsureToolFiles(true))
            {
                Debug.LogError("[unity-index] could not write tools/*.py");
                EditorApplication.Exit(1);
                return;
            }

            if (!ResolvePython(out string probe))
            {
                Debug.LogError($"[unity-index] {probe}");
                EditorApplication.Exit(2);
                return;
            }

            Debug.Log($"[unity-index] {probe}");
            EnsureGitIgnore(ProjectRoot);

            var build = RunSync(s_python, ScriptArg("unity_object_index.py", string.Empty), 600000, ProjectRoot);
            Debug.Log($"[unity-index] build\n{build.output}");
            if (build.code != 0)
            {
                EditorApplication.Exit(3);
                return;
            }

            var hooks = RunSync(s_python, ScriptArg("unity_refresh.py", "--install-hooks"), 120000, ProjectRoot);
            Debug.Log($"[unity-index] hooks\n{hooks.output}");
            EditorApplication.Exit(0);
        }

        #endregion

        #region Install helpers

        static bool EnsureToolFiles(bool silent = false)
        {
            if (AllToolsPresent())
                return true;

            if (WriteEmbeddedToolchain(false))
            {
                Debug.Log($"[unity-index] unpacked tools/*.py into {ToolsDir}");
                return true;
            }

            if (!s_missingWarned)
                Debug.LogError($"[unity-index] could not write tools/*.py into {ToolsDir} - see the Console");
            s_missingWarned = true;
            return false;
        }

        /// <summary>
        /// The .unitypackage cannot carry files outside Assets/, so the python
        /// scripts travel as base64 inside UnityIndexPayload.cs and are written
        /// to &lt;project&gt;/tools/ here.
        /// </summary>
        static bool WriteEmbeddedToolchain(bool force)
        {
            try
            {
                Directory.CreateDirectory(ToolsDir);
                string[] names = UnityIndexPayload.FileNames;
                for (int i = 0; i + 1 < names.Length; i += 2)
                {
                    string path = Path.Combine(ToolsDir, names[i]);
                    if (force || !File.Exists(path))
                        File.WriteAllBytes(path, Convert.FromBase64String(names[i + 1]));
                }
                return AllToolsPresent();
            }
            catch (Exception e)
            {
                Debug.LogException(e);
                return false;
            }
        }

        static bool AllToolsPresent()
        {
            foreach (string file in ToolFiles)
                if (!File.Exists(Path.Combine(ToolsDir, file)))
                    return false;
            return true;
        }

        static void CopyToolchain(string target)
        {
            string targetTools = Path.Combine(target, "tools");
            Directory.CreateDirectory(targetTools);

            foreach (string file in ToolFiles)
                File.Copy(Path.Combine(ToolsDir, file), Path.Combine(targetTools, file), true);

            string config = Path.Combine(ToolsDir, "unity_index_config.json");
            string targetConfig = Path.Combine(targetTools, "unity_index_config.json");
            if (File.Exists(config) && !File.Exists(targetConfig))
                File.Copy(config, targetConfig);

            var scripts = EditorScripts();
            if (scripts.Count > 0)
            {
                string editorDir = Path.Combine(target, "Assets", "Editor");
                Directory.CreateDirectory(editorDir);
                foreach (string script in scripts)
                    File.Copy(script, Path.Combine(editorDir, Path.GetFileName(script)), true);
            }
            else
            {
                Debug.LogWarning("[unity-index] editor scripts not found in AssetDatabase, target has no menu");
            }

            EnsureGitIgnore(target);
            Debug.Log($"[unity-index] copied toolchain to {target}");
        }

        /// <summary>Every editor script of the toolchain (menu + embedded payload).</summary>
        static List<string> EditorScripts()
        {
            var found = new List<string>();
            foreach (string term in new[] { "UnityIndexTool t:MonoScript", "UnityIndexPayload t:MonoScript" })
            {
                foreach (string guid in AssetDatabase.FindAssets(term))
                {
                    string path = AssetDatabase.GUIDToAssetPath(guid);
                    string name = Path.GetFileName(path);
                    if ((name == "UnityIndexTool.cs" || name == "UnityIndexPayload.cs")
                        && File.Exists(path)
                        && !found.Contains(Path.GetFullPath(path)))
                        found.Add(Path.GetFullPath(path));
                }
            }
            return found;
        }

        static void EnsureGitIgnore(string root)
        {
            string path = Path.Combine(root, ".gitignore");
            string text = File.Exists(path) ? File.ReadAllText(path) : string.Empty;
            if (text.Replace("\r", string.Empty).Contains(".unity-index/"))
                return;

            if (text.Length > 0 && !text.EndsWith("\n"))
                text += "\n";
            if (text.Length > 0)
                text += "\n";

            File.WriteAllText(path, text + GitIgnoreBlock);
            Debug.Log($"[unity-index] added .unity-index/ to {path}");
        }

        #endregion

        #region Python

        static bool ResolvePython(out string message)
        {
            if (s_python != null)
            {
                message = $"python: {s_python} {s_pythonArgs}";
                return true;
            }

            var candidates = new List<(string exe, string args)>();
            string configured = EditorPrefs.GetString(PythonKey, string.Empty);
            if (!string.IsNullOrEmpty(configured))
                candidates.Add((configured, string.Empty));
            candidates.Add(("python", string.Empty));
            candidates.Add(("py", "-3"));
            candidates.Add(("python3", string.Empty));

            var failures = new StringBuilder();
            foreach (var candidate in candidates)
            {
                string args = string.IsNullOrEmpty(candidate.args)
                    ? ScriptProbe
                    : candidate.args + " " + ScriptProbe;
                var result = RunSync(candidate.exe, args, 25000, ProjectRoot);
                if (result.code == 0)
                {
                    s_python = candidate.exe;
                    s_pythonArgs = candidate.args;
                    message = $"python: {candidate.exe} {candidate.args} ({result.output.Trim()})";
                    return true;
                }
                failures.AppendLine($"{candidate.exe}: {FirstLine(result.output)}");
            }

            message = "No working Python 3 + PyYAML found.\n\n"
                      + "Install Python 3 and run:  pip install pyyaml\n"
                      + "or point at it with Tools/Unity Index/Set Python Path.\n\n"
                      + failures;
            return false;
        }

        static string ScriptArg(string script, string extra)
        {
            string args = Quote(Path.Combine(ToolsDir, script));
            return string.IsNullOrEmpty(extra) ? args : args + " " + extra;
        }

        static void RunPythonAsync(string label, string script, string extra, string workdir, Action<int, string> done)
        {
            if (s_busy)
            {
                Debug.LogWarning("[unity-index] another job is running, skipped");
                return;
            }
            if (!ResolvePython(out string probe))
            {
                Debug.LogWarning($"[unity-index] {probe}");
                return;
            }

            string args = string.IsNullOrEmpty(s_pythonArgs) ? string.Empty : s_pythonArgs + " ";
            args += Quote(Path.Combine(workdir, "tools", script));
            if (!string.IsNullOrEmpty(extra))
                args += " " + extra;

            string exe = s_python;
            s_busy = true;
            if (!Application.isBatchMode)
                EditorUtility.DisplayProgressBar("Unity Index", label, 0.5f);

            var thread = new Thread(() =>
            {
                var result = RunSync(exe, args, 600000, workdir);
                s_mainThread.Enqueue(() =>
                {
                    s_busy = false;
                    if (!Application.isBatchMode)
                        EditorUtility.ClearProgressBar();
                    done(result.code, result.output);
                });
            }) { IsBackground = true };
            thread.Start();
        }

        static (int code, string output) RunSync(string exe, string args, int timeoutMs, string workdir)
        {
            var start = new System.Diagnostics.ProcessStartInfo(exe, args)
            {
                CreateNoWindow = true,
                UseShellExecute = false,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                WorkingDirectory = workdir,
            };
            start.EnvironmentVariables["PYTHONIOENCODING"] = "utf-8";
            start.EnvironmentVariables["PYTHONUTF8"] = "1";

            try
            {
                using (var process = System.Diagnostics.Process.Start(start))
                {
                    if (process == null)
                        return (-1, "could not start " + exe);

                    var stdout = process.StandardOutput.ReadToEndAsync();
                    var stderr = process.StandardError.ReadToEndAsync();
                    if (!process.WaitForExit(timeoutMs))
                    {
                        try { process.Kill(); } catch { /* already gone */ }
                        return (-2, "timed out after " + timeoutMs / 1000 + "s");
                    }

                    return (process.ExitCode, stdout.Result + stderr.Result);
                }
            }
            catch (Exception e)
            {
                return (-1, e.Message);
            }
        }

        static string FirstLine(string text)
        {
            if (string.IsNullOrEmpty(text))
                return "(no output)";
            int cut = text.IndexOf('\n');
            return (cut < 0 ? text : text.Substring(0, cut)).Trim();
        }

        static string Quote(string path)
        {
            return "\"" + path.Replace("\"", "\\\"") + "\"";
        }

        #endregion

        #region Auto refresh

        internal static bool HasUnityAsset(string[] paths)
        {
            foreach (string path in paths)
            {
                string lower = path.ToLowerInvariant();
                foreach (string extension in UnityExtensions)
                    if (lower.EndsWith(extension))
                        return true;
            }
            return false;
        }

        internal static void ScheduleAutoRefresh()
        {
            if (!EditorPrefs.GetBool(AutoRefreshKey, false))
                return;
            if (Application.isPlaying)
                return;
            s_refreshAt = EditorApplication.timeSinceStartup + 4.0;
        }

        #endregion
    }

    /// <summary>Only reacts when Tools/Unity Index/Auto Refresh On Save is enabled.</summary>
    sealed class UnityIndexAutoRefresh : AssetPostprocessor
    {
        static void OnPostprocessAllAssets(
            string[] imported, string[] deleted, string[] moved, string[] movedFrom)
        {
            if (!EditorPrefs.GetBool(UnityIndexTool.AutoRefreshKey, false))
                return;
            if (UnityIndexTool.HasUnityAsset(imported)
                || UnityIndexTool.HasUnityAsset(deleted)
                || UnityIndexTool.HasUnityAsset(moved))
                UnityIndexTool.ScheduleAutoRefresh();
        }
    }
